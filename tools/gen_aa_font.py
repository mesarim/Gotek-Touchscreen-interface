#!/usr/bin/env python3
"""Generate firmware/Gotek_JC3248/aa_font_data.h: the anti-aliased screen font (A600-aa1).

One font (Inter, SIL OFL 1.1) in the three calm text sizes. Each size fills the same box the
6x8 pixel font filled at 2x / 3x / 4x (16 / 24 / 32 px high), so a text keeps its y and its row.
Glyphs: ASCII 32..126 and Latin-1 160..255, 4 bits of coverage per pixel, cropped to their ink.

    python tools/gen_aa_font.py <Inter[opsz,wght].ttf> firmware/Gotek_JC3248/aa_font_data.h

The font file is not kept in the repo: https://github.com/google/fonts/tree/main/ofl/inter
"""
import sys
from PIL import Image, ImageDraw, ImageFont

WEIGHT = 600                      # SemiBold: holds up on the dark NEO backgrounds at 16 px
SIZES = (                         # (box height, em size, baseline from the box top)
    (16, 15, 13),
    (24, 22, 19),
    (32, 30, 26),
)
CHARS = list(range(32, 127)) + list(range(160, 256))


def render(path, box, em, base):
    font = ImageFont.truetype(path, em)
    font.set_variation_by_axes([min(max(em, 14), 32), WEIGHT])
    glyphs, bits = [], bytearray()
    for cp in CHARS:
        ch = chr(cp)
        adv = int(round(font.getlength(ch)))
        canvas = Image.new("L", (em * 2, box * 2), 0)
        ImageDraw.Draw(canvas).text((em // 2, base + box // 2), ch, fill=255, font=font, anchor="ls")
        bb = canvas.getbbox()
        if bb is None or cp == 32 or cp == 160:
            glyphs.append((len(bits), 0, 0, 0, 0, adv))
            continue
        x0, y0, x1, y1 = bb
        w, h = x1 - x0, y1 - y0
        dx, dy = x0 - em // 2, y0 - box // 2
        off = len(bits)
        nib = []
        for y in range(y0, y1):
            for x in range(x0, x1):
                nib.append((canvas.getpixel((x, y)) * 15 + 127) // 255)
        if len(nib) & 1:
            nib.append(0)
        for i in range(0, len(nib), 2):
            bits.append(nib[i] << 4 | nib[i + 1])
        glyphs.append((off, w, h, dx, dy, adv))
    return glyphs, bits


def main():
    src, out = sys.argv[1], sys.argv[2]
    lines = [
        "// Generated by tools/gen_aa_font.py - do not edit.",
        "// Inter (c) 2020 The Inter Project Authors, SIL Open Font License 1.1 (https://openfontlicense.org).",
        f"// Weight {WEIGHT}; ASCII 32..126 + Latin-1 160..255; 4-bit coverage, two pixels per byte, high nibble first.",
        "#pragma once",
        '#include "aa_text.h"',
        "",
    ]
    total = 0
    names = []
    for box, em, base in SIZES:
        glyphs, bits = render(src, box, em, base)
        name = f"aaInter{box}"
        names.append(name)
        total += len(bits) + len(glyphs) * 8
        lines.append(f"static const uint8_t {name}Bits[{len(bits)}] PROGMEM = {{")
        for i in range(0, len(bits), 24):
            lines.append("  " + ",".join(f"0x{b:02x}" for b in bits[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const AaGlyph {name}Glyphs[{len(glyphs)}] PROGMEM = {{")
        for off, w, h, dx, dy, adv in glyphs:
            lines.append(f"  {{{off},{w},{h},{dx},{dy},{adv}}},")
        lines.append("};")
        lines.append(f"static const AaFont {name} = {{ {name}Bits, {name}Glyphs, {box} }};")
        lines.append("")
    lines.append("// The font for a calm text size (2 / 3 / 4 = 16 / 24 / 32 px); other sizes stay on the pixel font.")
    lines.append("inline const AaFont* aaFontFor(int size) {")
    lines.append("  return " + " : ".join(f"size == {k + 2} ? &{n}" for k, n in enumerate(names)) + " : nullptr;")
    lines.append("}")
    lines.append(f"// {total} bytes in all")
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out}: {total} bytes")


if __name__ == "__main__":
    main()
