#!/usr/bin/env python3
"""Regenerate shared/app_page.h and shared/app_fonts.h from shared/app (the one app of every device, UI unity):

    python firmware/shared/app/make_app.py

The sources are FluxDrive's firmware/web, copied as they are (the app asks /api/system/info what a device can do and
shows only that). app.html gets tokens.css for /*@tokens*/ and app_logic.js plus every ui_*.js (by name) for
/*@scripts*/, gzip -9 with mtime 0: app_page_gz, served at / with gzip encoding. fonts/inter-latin.woff2 as it is:
inter_latin_woff2, at /fonts/inter-latin.woff2.
"""
import gzip
import pathlib

APP = pathlib.Path(__file__).resolve().parent
OUT = APP.parent


def read(name):
    return (APP / name).read_text(encoding="utf-8")


def array(name, data, comment):
    lines = [f"// {comment}", f"const unsigned int {name}_len = {len(data)};", f"const unsigned char {name}[] PROGMEM = {{"]
    for i in range(0, len(data), 16):
        lines.append("  " + ",".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    head = "// Generated by firmware/shared/app/make_app.py from firmware/shared/app - do not edit.\n#pragma once\n#include <pgmspace.h>\n\n"
    scripts = read("app_logic.js") + "".join(read(p.name) for p in sorted(APP.glob("ui_*.js")))
    app = read("app.html").replace("/*@tokens*/", read("tokens.css")).replace("/*@scripts*/", scripts)
    data = gzip.compress(app.encode("utf-8"), compresslevel=9, mtime=0)
    (OUT / "app_page.h").write_text(head + array("app_page_gz", data, f"app.html: {len(app.encode())} bytes"),
                                    encoding="utf-8", newline="\n")
    font = (APP / "fonts/inter-latin.woff2").read_bytes()
    (OUT / "app_fonts.h").write_text(
        head + array("inter_latin_woff2", font, "Inter (SIL OFL 1.1, shared/app/fonts/OFL.txt), Latin, weights 100-900"),
        encoding="utf-8", newline="\n")
    print(f"app {len(data)} B gzipped, font {len(font)} B")


if __name__ == "__main__":
    main()
